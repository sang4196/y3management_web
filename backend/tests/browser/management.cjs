'use strict';
module.exports=async function({page,api,login,master,branch,cfg,setStage}){
 const checks={};setStage('management-observer');
 const observer=await page();
 checks.second_browser_login=(await login(observer,cfg.masterPassword,'master.test')).status===204;
 const observerMe=await api(observer.p,'/auth/me'),masterMe=await api(master.p,'/auth/me');
 const first=(await master.context.cookies()).find(c=>c.name==='__Host-y3-auth');
 const twin=(await observer.context.cookies()).find(c=>c.name==='__Host-y3-auth');
 checks.independent_master_sessions=!!first&&!!twin&&first.value!==twin.value&&observerMe.status===200&&masterMe.status===200&&observerMe.body.account_id===masterMe.body.account_id;
 setStage('management-master');
 const issued=await api(master.p,'/admin/master-accounts',{login_id:'browser.master.two'});
 checks.master_issued=issued.status===201&&issued.body.admin_scope.kind==='ORGANIZATION';
 const other=await page();const raw=issued.body.setup_link.split('#token=')[1];let leaked=false;
 other.p.on('request',r=>{if(r.url().includes(raw))leaked=true;});
 await other.p.goto(issued.body.setup_link);
 checks.master_setup_fragment=await other.p.evaluate(()=>location.hash==='');
 await other.p.locator('#password').fill(cfg.branchPassword);
 const completed=other.p.waitForResponse(r=>r.url().endsWith('/auth/credentials/complete'));
 await other.p.locator('#submit').click();checks.master_setup=(await completed).status()===204;
 checks.master_setup_no_auto_login=!(await other.context.cookies()).some(c=>c.name==='__Host-y3-auth')&&(await api(other.p,'/auth/me')).status===401;
 checks.master_setup_url_private=!leaked;
 checks.master_login=(await login(other,cfg.branchPassword,'browser.master.two')).status===204;
 checks.master_scope=(await api(other.p,'/branches')).body.total===2;
 await api(branch.p,'/auth/logout',{});
 return {checks,master,other,branch,ident:issued.body.account_id};
};
